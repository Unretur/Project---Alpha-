if __name__ == "__main__":

    # --------------------------------------------------------
    # 1. Load NIFTY
    # --------------------------------------------------------

    nifty_path = Path(
        "data/raw/market/nifty50_5m.csv"
    )

    nifty = pd.read_csv(
        nifty_path
    )

    nifty = normalize_datetime(
        nifty,
        "timestamp",
    )

    nifty = sort_by_datetime(
        nifty,
        "timestamp",
    )

    nifty = remove_duplicate_timestamps(
        nifty,
        "timestamp",
    )

    # --------------------------------------------------------
    # Validate NIFTY
    # --------------------------------------------------------

    validate_datetime_column(
        nifty,
        "timestamp",
    )

    validate_sorted(
        nifty,
        "timestamp",
    )

    validate_no_duplicates(
        nifty,
        "timestamp",
    )

    # --------------------------------------------------------
    # 2. Start aligned dataset
    # --------------------------------------------------------

    aligned = nifty.copy()

    # --------------------------------------------------------
    # 3. Align FRED
    # --------------------------------------------------------

    print()
    print("Aligning FRED series...")

    for series_id, feature_name in FRED_SERIES.items():

        fred = load_fred_series(
            series_id,
            feature_name,
        )

        available_column = (
            f"{feature_name}_available_time"
        )

        validate_datetime_column(
            fred,
            available_column,
        )

        validate_sorted(
            fred,
            available_column,
        )

        validate_no_duplicates(
            fred,
            available_column,
        )

        aligned = align_asof(
            aligned,
            fred,
            left_on="timestamp",
            right_on=available_column,
        )

        validate_no_lookahead(
            aligned,
            decision_column="timestamp",
            available_column=available_column,
        )

        print(
            f"  ✓ {series_id} → {feature_name}"
        )

    # --------------------------------------------------------
    # 4. Align RBI
    # --------------------------------------------------------

    print()
    print("Aligning RBI series...")

    for filename, config in RBI_SERIES.items():

        available_column = config[
            "available_column"
        ]

        rbi = load_rbi_file(
            filename=filename,
            date_column=config["date_column"],
            available_column=available_column,
            features=config["features"],
        )

        validate_datetime_column(
            rbi,
            available_column,
        )

        validate_sorted(
            rbi,
            available_column,
        )

        validate_no_duplicates(
            rbi,
            available_column,
        )

        aligned = align_asof(
            aligned,
            rbi,
            left_on="timestamp",
            right_on=available_column,
        )

        validate_no_lookahead(
            aligned,
            decision_column="timestamp",
            available_column=available_column,
        )

        print(
            f"  ✓ {filename}"
        )

    # --------------------------------------------------------
    # 5. Resolve duplicate USD/INR columns
    # --------------------------------------------------------

    # When RBI exchange rates are enabled, both providers may
    # supply USD/INR. Rename the result without assuming RBI data
    # is present in every development environment.
    if "usd_inr_x" in aligned.columns:
        aligned = aligned.rename(
            columns={"usd_inr_x": "usd_inr_fred"}
        )
    elif "usd_inr" in aligned.columns:
        aligned = aligned.rename(
            columns={"usd_inr": "usd_inr_fred"}
        )

    if "usd_inr_y" in aligned.columns:
        aligned = aligned.rename(
            columns={"usd_inr_y": "usd_inr_rbi"}
        )

    # --------------------------------------------------------
    # 6. Save unified dataset
    # --------------------------------------------------------

    output_path = Path(
        "data/processed/nifty_macro_aligned.csv"
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    aligned.to_csv(
        output_path,
        index=False,
    )

    # --------------------------------------------------------
    # 7. Summary
    # --------------------------------------------------------

    print()
    print("=" * 60)
    print("NIFTY + FRED + RBI ALIGNMENT COMPLETED")
    print("=" * 60)

    print()
    print("NIFTY rows:", len(nifty))
    print("Final aligned rows:", len(aligned))

