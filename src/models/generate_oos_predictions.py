"""Generate expanding-window out-of-sample predictions for backtesting.

Each prediction is generated by a Ridge model trained only on earlier rows.
Output CSVs are separated by horizon and include the matching realized target.
They are research artifacts, not live signals or evidence of profitability.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from sklearn.linear_model import Ridge
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from src.models.baseline import DATASET_PATH, HORIZONS, build_feature_frame

OUTPUT_DIR = Path("data/processed/oos_predictions")
N_SPLITS = 4
MIN_TRAIN_FRACTION = 0.50


def generate_oos_predictions(
    dataset: pd.DataFrame,
    *,
    n_splits: int = N_SPLITS,
    min_train_fraction: float = MIN_TRAIN_FRACTION,
    selected_features: list[str] | None = None,
) -> dict[int, pd.DataFrame]:
    """Return one chronological OOS prediction frame per target horizon."""
    if n_splits < 2:
        raise ValueError("n_splits must be at least 2.")
    if not 0 < min_train_fraction < 1:
        raise ValueError("min_train_fraction must be between 0 and 1.")

    frame, available_features = build_feature_frame(dataset)
    features = list(selected_features) if selected_features is not None else available_features
    if not features:
        raise ValueError("At least one feature is required.")
    missing = set(features).difference(available_features)
    if missing:
        raise ValueError(f"Unknown selected features: {sorted(missing)}")
    if len(set(features)) != len(features):
        raise ValueError("Feature list contains duplicates.")

    frame[features] = frame[features].replace([np.inf, -np.inf], np.nan)
    frame = frame.sort_values("timestamp").reset_index(drop=True)
    n_rows = len(frame)
    first_test = int(n_rows * min_train_fraction)
    if n_rows - first_test < n_splits:
        raise ValueError("Not enough rows for requested OOS folds.")
    boundaries = np.linspace(first_test, n_rows, n_splits + 1, dtype=int)
    if len(set(boundaries)) != len(boundaries):
        raise ValueError("Not enough rows for distinct OOS folds.")

    output: dict[int, pd.DataFrame] = {}
    for horizon in HORIZONS:
        target = f"target_return_{horizon}m"
        fold_frames: list[pd.DataFrame] = []
        for fold in range(n_splits):
            start_i, end_i = int(boundaries[fold]), int(boundaries[fold + 1])
            test_start = frame.loc[start_i, "timestamp"]
            test_end = frame.loc[end_i, "timestamp"] if end_i < n_rows else None

            train = frame.loc[
                frame["timestamp"] + pd.Timedelta(minutes=horizon) < test_start
            ].dropna(subset=features + [target])
            mask = frame["timestamp"] >= test_start
            if test_end is not None:
                mask &= frame["timestamp"] < test_end
            test = frame.loc[mask].dropna(subset=features + [target])
            if train.empty or test.empty:
                raise ValueError(
                    f"Insufficient rows for {horizon}m fold {fold + 1}: "
                    f"train={len(train)}, test={len(test)}."
                )

            x_train = train[features].to_numpy(dtype=float)
            x_test = test[features].to_numpy(dtype=float)
            y_train = train[target].to_numpy(dtype=float)
            y_test = test[target].to_numpy(dtype=float)
            if not all(np.isfinite(x).all() for x in (x_train, x_test, y_train, y_test)):
                raise ValueError(f"Non-finite values in {horizon}m fold {fold + 1}.")

            model = make_pipeline(StandardScaler(), Ridge(alpha=1.0))
            model.fit(x_train, y_train)
            predictions = model.predict(x_test)
            fold_frames.append(pd.DataFrame({
                "timestamp": test["timestamp"].to_numpy(),
                "predicted_return": predictions,
                "actual_forward_return": y_test,
                "horizon_minutes": horizon,
                "fold": fold + 1,
                "train_end": train["timestamp"].max().isoformat(),
            }))

        result = pd.concat(fold_frames, ignore_index=True).sort_values("timestamp")
        if result["timestamp"].duplicated().any():
            raise ValueError(f"Duplicate OOS timestamps for horizon {horizon}m.")
        output[horizon] = result.reset_index(drop=True)
    return output


def main() -> None:
    if not DATASET_PATH.is_file():
        raise FileNotFoundError(f"Dataset not found: {DATASET_PATH}")
    results = generate_oos_predictions(pd.read_csv(DATASET_PATH))
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    summary: dict[str, Any] = {}
    for horizon, frame in results.items():
        path = OUTPUT_DIR / f"nifty_{horizon}m_oos_predictions.csv"
        frame.to_csv(path, index=False)
        mae = float(np.mean(np.abs(
            frame["actual_forward_return"] - frame["predicted_return"]
        )))
        zero_mae = float(np.mean(np.abs(frame["actual_forward_return"])))
        summary[f"{horizon}m"] = {
            "rows": int(len(frame)),
            "start": frame["timestamp"].min().isoformat(),
            "end": frame["timestamp"].max().isoformat(),
            "model_mae": mae,
            "zero_return_mae": zero_mae,
            "mae_improvement_pct": (1 - mae / zero_mae) * 100 if zero_mae else None,
            "csv": str(path),
        }
        print(
            f"{horizon}m: rows={len(frame)}, model_MAE={mae:.8f}, "
            f"zero_MAE={zero_mae:.8f}, "
            f"MAE_improvement={summary[f'{horizon}m']['mae_improvement_pct']:.2f}%"
        )
        print(f"Saved: {path}")
    (OUTPUT_DIR / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
