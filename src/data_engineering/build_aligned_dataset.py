from pathlib import Path

import pandas as pd

from src.data_engineering.normalize import (
    normalize_datetime,
    sort_by_datetime,
    remove_duplicate_timestamps,
)

from src.data_engineering.time_alignment import align_asof

from src.data_engineering.validation import (
    validate_datetime_column,
    validate_sorted,
    validate_no_duplicates,
    validate_no_lookahead,
)


# ============================================================
# FRED SERIES
# ============================================================

FRED_SERIES = {
    "VIXCLS": "vix",
    "DGS10": "us10y",
    "DFF": "fed_funds",
    "DEXINUS": "usd_inr",
}


# ============================================================
# RBI SERIES
# ============================================================

# Optional: these files are generated by src.ingestion.rbi.parser.
# Keep the pipeline runnable when the source PDFs are not present.
RBI_SERIES = {}


# ============================================================
# FRED LOADER
# ============================================================

def load_fred_series(
    series_id: str,
    feature_name: str,
) -> pd.DataFrame:

    path = Path(
        f"data/raw/fred/{series_id}.csv"
    )

    df = pd.read_csv(path)

    df = normalize_datetime(
        df,
        "date",
    )

    df = sort_by_datetime(
        df,
        "date",
    )

    df = remove_duplicate_timestamps(
        df,
        "date",
    )

    df = df.rename(
        columns={
            "date": f"{feature_name}_available_time",
            "value": feature_name,
        }
    )

    return df


# ============================================================
# RBI LOADER
# ============================================================

def load_rbi_file(
    filename: str,
    date_column: str,
    available_column: str,
    features: list[str],
) -> pd.DataFrame:

    path = Path(
        f"data/raw/rbi/{filename}"
    )

    df = pd.read_csv(path)

    df = normalize_datetime(
        df,
        date_column,
    )

    df = sort_by_datetime(
        df,
        date_column,
    )

    df = remove_duplicate_timestamps(
        df,
        date_column,
    )

    df = df[
        [date_column] + features
    ].copy()

    df = df.rename(
        columns={
            date_column: available_column
        }
    )

    return df


